import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { _electron as electron } from 'playwright-core';
import { fixture, output } from '../test/helpers.mjs';

const require = createRequire(import.meta.url);
const appearance = JSON.parse(await fs.readFile(new URL('../core/window-appearance.json', import.meta.url)));
const rgb = hex => 'rgb(' + hex.slice(1).match(/../g).map(part => parseInt(part, 16)).join(', ') + ')';
const f = await fixture('draft-reading-layout');
const w = f.workspace;
const long = '# 第五章 长廊\n\n' + Array.from({ length: 65 }, (_, i) => `阿青沿着长廊走到第${i + 1}扇窗前，听见雨落在檐上。\n\n`).join('');
await w.createChapterDraft({ chapter: 5, title: '长廊', importedText: long });
const main = await w.createChapterDraft({ chapter: 6, title: '渡船', importedText: '# 第六章 渡船\n\n这里是保存前的句子。\n' });
const alternate = await w.createChapterDraft({ chapter: 6, title: '石桥', importedText: '# 第六章 石桥\n\n这里是另一份草稿。\n' });
await w.saveDocument({ documentId: main.id, expectedHash: main.hash, text: '# 第六章 渡船\n\n这里是最新保存的句子。\n' });
await f.close();

const packaged = process.env.NOVEL_PACKAGED_EXE;
const env = { ...process.env, NOVEL_TEST_MODE: '1', NOVEL_DEFAULT_WORK: f.root, NOVEL_USER_DATA: path.join(f.root, 'runtime') };
delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  app = await electron.launch({ executablePath: packaged || require('electron'), args: packaged ? [] : [process.cwd()], env, timeout: 45000 });
  const page = await app.firstWindow();
  page.setDefaultTimeout(10000);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByLabel('外观主题', { exact: true }).selectOption('charcoal');
  await page.getByRole('button', { name: '打开工作区', exact: true }).click();
  await page.getByRole('button', { name: /正文与草稿/ }).click();
  const pane = page.locator('#workspace-tool-content');
  const button = name => pane.getByRole('button', { name, exact: true });
  await button('草稿').click();
  await pane.getByRole('button', { name: /第五章 长廊/ }).click();
  const editor = pane.locator('.manuscript-editor');
  await editor.waitFor();
  assert.equal(await pane.getByText('正文目录', { exact: true }).count(), 0);
  assert.equal(await pane.locator('.reader-status .badge').count(), 1);
  const scroll = editor.locator('.cm-scroller');
  const toolbar = pane.locator('.reader-toolbar');
  const before = (await toolbar.boundingBox()).y;
  assert.ok((await editor.boundingBox()).height > (await pane.boundingBox()).height * 0.8);
  await scroll.evaluate(node => { node.scrollTop = node.scrollHeight; });
  assert.ok(await scroll.evaluate(node => node.scrollTop) > 100);
  assert.equal(await pane.evaluate(node => node.scrollTop), 0);
  assert.equal((await toolbar.boundingBox()).y, before);
  await pane.screenshot({ path: path.join(output, '2.0.9-草稿滚动.png') });
  await button('更多').click();
  const more = pane.locator('.reader-popover:popover-open');
  await more.getByRole('button', { name: '核对并发布', exact: true }).waitFor();
  assert.equal(await more.getByRole('button', { name: '创作本章', exact: true }).count(), 0);
  assert.equal(await more.getByRole('button', { name: '版本比较', exact: true }).count(), 0);
  await page.keyboard.press('Escape');

  await button('稿件资料').click();
  const info = pane.locator('.reader-popover:popover-open');
  await info.getByRole('button', { name: '阿青', exact: true }).waitFor();
  await info.getByText('本地来源', { exact: true }).waitFor();
  assert.equal(await info.getByText('归档事件', { exact: true }).count(), 0);
  await page.keyboard.press('Escape');
  await button('阅读设置').click();
  const settings = pane.locator('.reader-popover:popover-open');
  assert.equal(await settings.getByLabel('阅读配色').inputValue(), 'follow');
  await settings.getByRole('button', { name: '放大字号' }).click();
  assert.equal(await settings.getByLabel('当前字号').innerText(), '20');
  assert.equal(await settings.evaluate(el => getComputedStyle(el).backgroundColor), rgb(appearance.charcoal.paper));
  await pane.screenshot({ path: path.join(output, '2.0.9-阅读设置.png') });
  await page.keyboard.press('Escape');

  const body = editor.getByRole('textbox', { name: '正文编辑区', exact: true });
  await body.press('Control+Home');
  await body.press('Shift+End');
  const selected = editor.locator('.cm-selectionBackground').first();
  assert.equal(await selected.evaluate(el => getComputedStyle(el).backgroundColor), rgb(appearance.charcoal.selection));
  await button('引用到对话').click();
  await page.getByLabel('本轮引用').getByRole('button', { name: '@第五章 长廊', exact: true }).waitFor();

  const list = () => page.getByLabel('工作区标签').getByRole('button', { name: '正文与草稿', exact: true }).click();
  await list();
  await pane.getByRole('button', { name: /第六章 渡船/ }).click();
  await button('更多').click();
  await pane.locator('.reader-popover:popover-open').getByRole('button', { name: '版本比较', exact: true }).click();
  const version = page.getByRole('dialog', { name: '版本比较', exact: true });
  await version.getByText('这里是保存前的句子。', { exact: false }).waitFor();
  await version.getByText('这里是最新保存的句子。', { exact: false }).waitFor();
  await version.getByLabel('与当前稿件比较').selectOption(alternate.id);
  await version.getByText('这里是另一份草稿。', { exact: false }).waitFor();
  assert.equal(await version.getByRole('button', { name: '载入为编辑稿' }).count(), 0);
  assert.equal(await version.locator('.diff-columns > div').first().evaluate(el => getComputedStyle(el).backgroundColor), rgb(appearance.charcoal.ground));
  await version.screenshot({ path: path.join(output, '2.0.9-版本比较.png') });
  await version.getByRole('button', { name: '关闭比较', exact: true }).click();

  await list();
  await button('新建草稿').click();
  const create = page.getByRole('dialog', { name: '新建章节草稿', exact: true });
  await create.getByLabel('草稿章号').fill('7');
  await create.getByLabel('草稿标题').fill('手动建稿');
  await create.getByRole('button', { name: '创建草稿', exact: true }).click();
  await editor.getByText(/第07章.*手动建稿/).waitFor();
  const summary = await page.evaluate(() => window.storyDesk.call('summary'));
  const newDraft = summary.documents.find(item => item.chapter === 7 && item.kind === 'draft');
  assert.ok(newDraft);
  assert.match(await f.read(newDraft.path), /手动建稿/u);
  assert.equal(summary.documents.some(item => item.chapter === 7 && item.kind === 'chapter'), false);

  await page.setViewportSize({ width: 980, height: 780 });
  await page.getByLabel('外观主题', { exact: true }).selectOption('paper');
  await button('阅读设置').click();
  const narrowSettings = pane.locator('.reader-popover:popover-open');
  const bounds = await narrowSettings.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 980 && bounds.y + bounds.height <= 780);
  assert.equal(await narrowSettings.getByLabel('阅读配色').inputValue(), 'follow');
  assert.equal(await narrowSettings.evaluate(el => getComputedStyle(el).backgroundColor), rgb(appearance.paper.paper));
  await page.keyboard.press('Escape');
  await button('稿件核对').click();
  await pane.locator('.manuscript-review').waitFor();
  assert.equal(await pane.getByLabel('核对文稿', { exact: true }).inputValue(), newDraft.id);
  console.log('通过：草稿独立滚动、主题与窄窗口、按需资料、真实版本比较、引用、手动建稿及打开稿件核对。');
} finally { await app?.close(); }
